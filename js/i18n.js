export function pluralIndex(lang, n) {
  if (lang === 'sl') {
    const m = n % 100;
    return m === 1 ? 0 : m === 2 ? 1 : m === 3 || m === 4 ? 2 : 3;
  }
  return n === 1 ? 0 : 1;
}
